"""legged-loco `go2_base` (blind low-level policy used by NaVILA), ported from Isaac Lab 1.1 to Isaac Lab 2.x.

Differences to omni.isaac.leggedloco/config/go2/go2_low_base_cfg.py:
  * namespaces: omni.isaac.lab* -> isaaclab*, RSL-RL cfgs from isaaclab_rl
  * the proprioceptive history that legged-loco's RslRlVecEnvHistoryWrapper(history_length=9) concatenated to the
    policy input is now Isaac Lab's native observation history (group "proprio", history_length=9) and rsl-rl's
    obs_groups mapping {"actor": ["policy", "proprio"]}
  * sim.disable_contact_processing no longer exists (dropped)
Everything else (rewards, actuators, terrains, observation terms, events) is unchanged.
"""

